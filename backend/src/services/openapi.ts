import { DetectedRoute } from "../types";

// the scan already knows every route, its params and an example body. that is
// most of a spec, so emitting one costs a mapping rather than another model
// call. what it cannot know is written down as such instead of invented:
// response shapes are left unspecified rather than guessed at.

interface SpecOptions {
  title: string;
  baseUrl?: string;
}

function schemaFor(value: any): any {
  if (value === null) return { nullable: true };
  if (Array.isArray(value)) {
    return { type: "array", items: value.length ? schemaFor(value[0]) : {} };
  }
  switch (typeof value) {
    case "number":
      return { type: Number.isInteger(value) ? "integer" : "number", example: value };
    case "boolean":
      return { type: "boolean", example: value };
    case "object": {
      const properties: Record<string, any> = {};
      for (const [k, v] of Object.entries(value)) properties[k] = schemaFor(v);
      return { type: "object", properties };
    }
    default: {
      // the scan writes "string" as a placeholder for a value it did not see
      const text = String(value);
      return text === "string" ? { type: "string" } : { type: "string", example: text };
    }
  }
}

// /users/:id in express is /users/{id} in openapi
function toTemplate(path: string): { path: string; names: string[] } {
  const names: string[] = [];
  const converted = path.replace(/:([A-Za-z0-9_]+)/g, (_, name) => {
    names.push(name);
    return `{${name}}`;
  });
  return { path: converted, names };
}

export function buildOpenApi(routes: DetectedRoute[], opts: SpecOptions) {
  const paths: Record<string, any> = {};

  for (const route of routes) {
    const { path, names } = toTemplate(route.path);
    const method = String(route.method || "GET").toLowerCase();

    // path params are required by definition; anything else the scan listed is
    // treated as a query parameter
    const declared = Array.isArray(route.params) ? route.params : [];
    const parameters = [
      ...names.map((name) => ({
        name,
        in: "path",
        required: true,
        schema: { type: "string" },
      })),
      ...declared
        .filter((p) => !names.includes(String(p).replace(/^:/, "")))
        .map((p) => ({
          name: String(p).replace(/^:/, ""),
          in: "query",
          required: false,
          schema: { type: "string" },
        })),
    ];

    const operation: any = {
      summary: route.description || `${route.method} ${route.path}`,
      responses: {
        // no request was made to build this, so the shape is genuinely unknown
        default: { description: "Not captured by the scan" },
      },
    };

    if (parameters.length) operation.parameters = parameters;

    if (route.body && typeof route.body === "object") {
      operation.requestBody = {
        content: { "application/json": { schema: schemaFor(route.body) } },
      };
    }

    if (!paths[path]) paths[path] = {};
    paths[path][method] = operation;
  }

  return {
    openapi: "3.0.3",
    info: {
      title: opts.title,
      version: "0.0.0",
      description:
        "Generated by ReqFlow from a static scan of the source. Paths, parameters and request bodies come from the code; response shapes were not observed and are left unspecified.",
    },
    ...(opts.baseUrl ? { servers: [{ url: opts.baseUrl }] } : {}),
    paths,
  };
}
